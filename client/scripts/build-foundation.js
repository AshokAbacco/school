const manifestPath = path.join(
  androidAppDir,
  "src",
  "main",
  "AndroidManifest.xml",
);
if (
  fs.existsSync(manifestPath) &&
  (fs.existsSync(nativeDst) || fs.existsSync(nativeSrc))
) {
  let mf = fs.readFileSync(manifestPath, "utf8");
  const before = mf;

  // 0) Remove help comments pasted from AndroidManifest.busalerts.xml — they
  //    contain the text xmlns:tools="…" and fooled the checks below.
  mf = mf.replace(
    /<!--(?:(?!-->)[\s\S])*?(?:ADD these lines|tools namespace|Inside <application>|Inside <manifest>)[\s\S]*?-->\s*/g,
    "",
  );

  // 1) tools namespace must be on the ROOT <manifest> tag (not just anywhere)
  mf = mf.replace(/<manifest\b[^>]*>/, (tag) =>
    tag.includes("xmlns:tools=")
      ? tag
      : tag.replace(
          "<manifest",
          '<manifest xmlns:tools="http://schemas.android.com/tools"',
        ),
  );

  // 2) POST_NOTIFICATIONS must be a direct child of <manifest>, never inside <application>
  const permRe =
    /\s*<uses-permission\s+android:name="android\.permission\.POST_NOTIFICATIONS"\s*\/>/g;
  mf = mf.replace(/<application\b[\s\S]*?<\/application>/, (app) =>
    app.replace(permRe, ""),
  );
  const permCount = (mf.match(permRe) || []).length;
  if (permCount === 0) {
    mf = mf.replace(
      /(\n?\s*)(<application\b)/,
      '\n    <uses-permission android:name="android.permission.POST_NOTIFICATIONS" />\n\n    $2',
    );
  } else if (permCount > 1) {
    let seen = false;
    mf = mf.replace(permRe, (m) => (seen ? "" : ((seen = true), m)));
  }

  // 3) exactly one of each service entry, inside <application>
  const removeRe =
    /\s*<service\s+android:name="com\.capacitorjs\.plugins\.pushnotifications\.MessagingService"\s+tools:node="remove"\s*\/>/g;
  const ourRe =
    /\s*<service\s+android:name="com\.abacco\.busalerts\.BusAlertMessagingService"[\s\S]*?<\/service>/g;
  const removeCount = (mf.match(removeRe) || []).length;
  const ourCount = (mf.match(ourRe) || []).length;
  if (removeCount !== 1 || ourCount !== 1) {
    mf = mf.replace(removeRe, "").replace(ourRe, "");
    const block = `
        <!-- Bus alerts: replaces the Capacitor push receiver (extends it) and speaks alerts when the app is closed -->
        <service
            android:name="com.capacitorjs.plugins.pushnotifications.MessagingService"
            tools:node="remove" />
        <service
            android:name="com.abacco.busalerts.BusAlertMessagingService"
            android:exported="false">
            <intent-filter>
                <action android:name="com.google.firebase.MESSAGING_EVENT" />
            </intent-filter>
        </service>
    `;
    mf = mf.replace(/\s*<\/application>/, `\n${block}</application>`);
  }

  // 4) sanity check: every tools: attribute needs the namespace on <manifest>
  const rootTag = (mf.match(/<manifest\b[^>]*>/) || [""])[0];
  if (/\stools:/.test(mf) && !rootTag.includes("xmlns:tools=")) {
    console.error(
      "❌ AndroidManifest.xml uses tools: but <manifest> has no xmlns:tools — fix it by hand",
    );
    process.exit(1);
  }

  if (mf !== before) {
    fs.writeFileSync(manifestPath, mf);
    fs.writeFileSync(`${manifestPath}.bak`, before); // previous version, just in case
    console.log(
      "✅ AndroidManifest.xml: bus-alert service registered / repaired (backup: AndroidManifest.xml.bak)",
    );
  } else {
    console.log("✅ AndroidManifest.xml already has the bus-alert service");
  }
}


const firebaseTarget = path.join(androidAppDir, "google-services.json");
const skipFirebase = process.env.SKIP_FIREBASE === "1";

function firebaseFail(msg) {
  if (skipFirebase) {
    console.warn(`⚠️  ${msg}`);
    console.warn(
      "⚠️  SKIP_FIREBASE=1 → building WITHOUT bus alerts when the app is closed.",
    );
    if (fs.existsSync(firebaseTarget)) fs.rmSync(firebaseTarget);
    return;
  }
  console.error("");
  console.error(`❌ ${msg}`);
  console.error("");
  console.error(
    "   Fix: Firebase console → Project settings → Your apps → Add app → Android",
  );
  console.error(`        package name: ${config.appId}`);
  console.error(
    "        then download google-services.json again and save it as",
  );
  console.error("        client/firebase/google-services.json");
  console.error("");
  console.error(
    "   Or build without push:  SKIP_FIREBASE=1 npm run build:" + foundation,
  );
  console.error("");
  process.exit(1);
}

if (!firebaseSource) {
  firebaseFail("google-services.json not found in client/firebase/");
} else {
  let gs;
  try {
    gs = JSON.parse(fs.readFileSync(firebaseSource, "utf8"));
  } catch (e) {
    gs = null;
    firebaseFail(
      `${path.relative(clientDir, firebaseSource)} is not valid JSON (${
        e.message
      })`,
    );
  }
  if (gs) {
    const packages = (gs.client || [])
      .map((c) => c?.client_info?.android_client_info?.package_name)
      .filter(Boolean);
    if (!packages.includes(config.appId)) {
      firebaseFail(
        `${path.relative(clientDir, firebaseSource)} has no Android app "${
          config.appId
        }" ` + `(it has: ${packages.join(", ") || "none"})`,
      );
    } else {
      fs.copyFileSync(firebaseSource, firebaseTarget);
      console.log(
        `✅ Firebase config for ${config.appId} (project ${
          gs.project_info?.project_id || "?"
        }) → android/app/google-services.json`,
      );
    }
  }
}

